const DICTS: Record<Locale, Record<MsgKey, string>> = { en, hi };

export function t(locale: Locale, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = DICTS[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const categoryKey = (c: string): MsgKey => (c === "meals" ? "meals_" : (c as MsgKey));
